/// 环境光的"向阳暖化"强度。
///
/// 物理背景：真实房间里，环境光并非各向同性——窗侧（向阳）接收的是
/// 低层大气直射+悬粒散射的混合，色温明显低于天顶天光；房间深处
/// 以天顶天光为主。旧实现整面墙用同一份天顶色，于是"环境光完全不
/// 跟着太阳转"。
///
/// 视觉效果：调大 → 光斑周围的暖晕更明显、墙面"朝阳面/背阳面"冷暖
/// 对比增强；调小（=0）→ 回到各向同性天顶色（平灰）。
const double kAmbientSunWarmth = 0.45;

/// 环境光色温整体增益（对冷暖分离量的乘子）。
///
/// 物理背景：散射光谱计算的色温差在 8bit 输出上偏保守（sRGB 编码
/// 压缩暗部色差）。此乘子把物理正确但"不易察觉"的色温差放大到
/// 可感区间——不是伪造色温，是增益于已算出的色温差。
///
/// 视觉效果：调大 → 晨/暮的暖光与正午冷白对比更"出片"；调小 →
/// 全天色温趋于一致（寡淡）。
const double kAmbientChromaGain = 1.35;

/// 城市光污染的夜空亮度倍率（Walker 定律拟合后的缩放）。
///
/// 物理背景：cityGlow 参数本意是"夜空辉光相对自然底的倍增"
/// （市区≈2）。此前实现里夜晚分支直接把参数当倍数乘上去，加上
/// 自动曝光以中位亮度对焦，夜里整面墙被抬高到"像开灯"。
///
/// 视觉效果：调大 → 市区夜更亮、泛红橙更明显；调小（=1）→ 只有
/// 自然夜空。此常数是对 cityGlow **输入值**的缩放（0.5 → 市区输入
/// 2.0 实际生效 1.0 倍），让默认参数落在不夸张的区间。
const double kCityGlowScale = 0.5;

/// 暮光分支的城市光污染衰减。
///
/// 物理背景：暮光时天空仍有自然亮度，光污染相对贡献比深夜小。
///
/// 视觉效果：调大 → 黄昏城市橙霾更浓；调小 → 暮光更"自然纯净"。
const double kCityGlowTwilightScale = 0.25;

/// 室内灯的环境耦合系数（indoorLight 相对量 → 墙面照度）。
///
/// 物理背景：室内灯的绝对流明与房间尺度耦合，难以从参数直接推；
/// 此系数把"相对强度 1.0"映射到与夜天光同量级的墙面照度。
///
/// 视觉效果：调大 → 夜里开灯的暖底更亮；调小 → 夜晚更冷清。
const double kIndoorLightScale = 0.6;

/// 月光的**珀金杰位移**（观察者模型：色度保留比例）。
///
/// 物理背景：月光 0.1~0.3 lux 处于中间视觉下段，视杆细胞（峰值 507 nm）
/// 主导、无色彩分辨能力——场景色彩感知大幅褪色。这是"银白月夜"的
/// 生理学来源：月面反射谱本身微偏红（月壤铁吸收，保留在光源光谱里
/// 不动），银白感来自**观察者降饱和**，不是月光真的偏蓝。
///
/// 实现：合成端对月光场景的饱和度乘以此系数（1.0 = 色彩保留）。
///
/// 视觉效果：调小（→0）→ 月夜完全褪成黑白"冷银"；调大（→1）→
/// 色彩保留，月光场景会显出材质本色（偏暖）——生理上不真实。
const double kMoonPurkinjeShift = 0.25;

/// 月光场景的**自动曝光目标缩放**（对显示中灰 0.18 的乘子）。
///
/// 物理背景：自动测光把月夜拉到中灰 = "月夜亮得像白天"。真实相机
/// 长曝月夜照片与暗适应人眼的感受都是**暗调**（Hunt 效应：低亮度级
/// 下感知明度整体下移）。满月夜照片中位亮度经验在中灰的 1/6~1/8。
///
/// 视觉效果：调大 → 月夜更亮（银白但失去夜感）；调小 → 更暗、
/// 光斑更突出（低钥匙 low-key）。
const double kMoonTargetScale = 0.30;

/// 无月夜空场景的自动曝光目标缩放。
///
/// 物理背景同上。无月夜更暗（仅气辉+星光），目标约中灰的 1/12。
///
/// 视觉效果：调大 → 星空夜可见更多室内细节；调小 → 近乎全黑只余
/// 窗外夜空辉光。
const double kNightTargetScale = 0.08;

// ────────────── 成像层（参考真实墙面照片的响应） ──────────────
//
// 用户提供的参考照片（暖斑冷影、暗部有层次、边缘柔和）对应的不是某个
// 物理参数，而是**相机/人眼的成像响应**：负片的趾部（暗部抬起）+ 肩部
// （高光滚降）+ 阴影由天光照亮带来的冷偏。以下常数集中表达这一层。

/// 暗部提升（胶片趾部 / 阴影提亮）。
///
/// 物理背景：真实照片的暗部不是线性压到 0——底片趾部、相机 tone curve、
/// 人眼暗适应都会把阴影抬到"有层次"的深灰。纯物理线性 + ACES 的暗部
/// 会过于死黑（Hunt 效应只解释了整体明度下移，未解释局部可读性）。
///
/// 视觉效果：调大 → 暗部更"灰"、细节更多但发闷；调小（=0）→ 死黑、
/// 舞台感强。
const double kFilmicShadowLift = 0.030;

/// 暗部提升的蓝色偏移（冷阴影）。
///
/// 物理背景：室内阴影区唯一的光源是**天光**（8000~12000 K），而光斑是
/// 直射阳光（2000~5500 K）。真实照片里"暖斑冷影"正是这个色温差的可视化。
/// 但纯物理算出的暗部色差在 8bit 下偏弱（暗部色度分辨率低），需要增益。
///
/// 视觉效果：调大 → 阴影越发蓝紫、与暖斑对比强烈；调小 → 中性灰阴影。
const double kShadowCoolShift = 0.35;

/// 高光滚降强度（肩部压缩）。
///
/// 物理背景：光斑亮度远超中间调，若不压缩会顶成死白一块（参考图里
/// 光斑内部仍能看到窗格线与材质）。胶片肩部与相机 highlight rolloff 负责
/// 把这段压回可视范围。
///
/// 视觉效果：调大 → 光斑更"奶"、层次更多但对比弱；调小 → 光斑死白。
const double kHighlightRolloff = 0.55;

/// 光斑边缘的**额外软化**（等效散射角，度）。
///
/// 物理背景：真实光斑边缘的软带比纯几何半影宽得多——来自 ① 窗玻璃体散射
/// 与表面粗糙度、② 墙面微观凹凸的多次漫射、③ 大气前向散射。纯几何半影
/// （太阳 0.53° 角径）在 3 m 距离只有 ~3 cm，参考照片的软带是 10~20 cm。
///
/// 视觉效果：调大 → 边缘更"雾"、像老镜头；调小（=0）→ 只剩几何半影。
const double kPenumbraScatterDeg = 0.12;

/// 环境光（天光漫射）**量级**系数。
///
/// 物理背景：窗对墙的双余弦还原因子已按物理算（Ĝ/I_h），但真实室内
/// 天光进入后经墙面多次漫反射会再损失；且相机测光对人眼感知的"阴影
/// 亮度"有压缩。此系数把环境光整体缩放，控制"暗部有多暗"。
///
/// 视觉效果：调大 → 暗部更亮（平、无戏剧性）；调小 → 暗部更深、
/// 光斑更突出（参考照片的低钥匙感）。
const double kAmbientScale = 0.22;

/// 自动测光的**目标亮度**（高光保留测光）。
///
/// 物理背景：墙面照片的曝光目标是"光斑刚好不过曝"，而不是"画面平均中灰"。
/// 中位测光在低钥匙场景（大片阴影 + 小光斑）会把暗部抬亮、光斑压平，
/// 观感是"灰蒙蒙、光不成型"。取 97 分位亮度对准此目标值。
///
/// 视觉效果：调大（→1）→ 光斑接近溢出、暗部更黑、戏剧性强；
/// 调小 → 整体更亮更平（回到中位测光的感觉）。
const double kHighlightTarget = 1.15;

/// auto 构图下，观察墙相对"背对太阳"的偏置角（度）。
///
/// 物理等价：拍摄者站在背光侧偏一点取景。偏置 0 时光斑死正投（形状不随
/// 太阳方位变化）；偏置越大，光斑越斜、拖影越长。
///
/// 视觉效果：调大 → 光斑更斜更长、画面更有透视感（但过大时贴边）；
/// 调小 → 光斑方正居中。
const double kViewSunBiasDeg = 18.0;

/// 环日散射（aureole）的角半宽（度）—— 决定光斑边缘的软带宽度。
///
/// 物理背景：aureole 是气溶胶前向散射形成的亮晕（真实天空约 1~3°）。
/// 但进入窗户后，这部分光同样被窗框与窗洞遮挡，因此它**不该**成为
/// 光斑边缘的厘米级模糊源。2° 在 4 m 距离 = 14 cm，会把窗格糊成一团
/// （实测：光斑只剩横向条纹、竖窗棂完全消失）。
///
/// 视觉效果：调大 → 光斑边缘雾化、窗格细节消失；调小 → 边缘更利、
/// 更接近清晰的窗形投影。
const double kAureoleHaloDeg = 0.35;
