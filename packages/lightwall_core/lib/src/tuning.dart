// 视觉调校常数白名单（Tuning Constants）
//
// ┌─────────────────────────────────────────────────────────────────┐
// │ 本文件是全仓库唯一允许"非物理推导"常数存在的地方。              │
// │ 每个常数必须注明：物理背景 → 偏离理由 → 视觉效果（调大/调小）   │
// │ 修这里 = 修观感；其余文件里的数值一律应有物理出处。             │
