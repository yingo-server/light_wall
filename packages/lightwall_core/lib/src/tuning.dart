/// 环境光的"向阳暖化"强度。
///
/// 物理背景：真实房间里，环境光并非各向同性——窗侧（向阳）接收的是
/// 低层大气直射+悬粒散射的混合，色温明显低于天顶天光；房间深处
/// 以天顶天光为主。旧实现整面墙用同一份天顶色，于是"环境光完全不
/// 跟着太阳转"。
///
/// 视觉效果：调大 → 光斑周围的暖晕更明显、墙面"朝阳面/背阳面"冷暖
/// 对比增强；调小（=0）→ 回到各向同性天顶色（平灰）。
const double kAmbientSunWarmth = 0.45;

/// 环境光色温整体增益（对冷暖分离量的乘子）。
///
/// 物理背景：散射光谱计算的色温差在 8bit 输出上偏保守（sRGB 编码
/// 压缩暗部色差）。此乘子把物理正确但"不易察觉"的色温差放大到
/// 可感区间——不是伪造色温，是增益于已算出的色温差。
///
/// 视觉效果：调大 → 晨/暮的暖光与正午冷白对比更"出片"；调小 →
/// 全天色温趋于一致（寡淡）。
const double kAmbientChromaGain = 1.35;

/// 城市光污染的夜空亮度倍率（Walker 定律拟合后的缩放）。
///
/// 物理背景：cityGlow 参数本意是"夜空辉光相对自然底的倍增"
/// （市区≈2）。此前实现里夜晚分支直接把参数当倍数乘上去，加上
/// 自动曝光以中位亮度对焦，夜里整面墙被抬高到"像开灯"。
///
/// 视觉效果：调大 → 市区夜更亮、泛红橙更明显；调小（=1）→ 只有
/// 自然夜空。此常数是对 cityGlow **输入值**的缩放（0.5 → 市区输入
/// 2.0 实际生效 1.0 倍），让默认参数落在不夸张的区间。
const double kCityGlowScale = 0.5;

/// 暮光分支的城市光污染衰减。
///
/// 物理背景：暮光时天空仍有自然亮度，光污染相对贡献比深夜小。
///
/// 视觉效果：调大 → 黄昏城市橙霾更浓；调小 → 暮光更"自然纯净"。
const double kCityGlowTwilightScale = 0.25;

/// 室内灯的环境耦合系数（indoorLight 相对量 → 墙面照度）。
///
/// 物理背景：室内灯的绝对流明与房间尺度耦合，难以从参数直接推；
/// 此系数把"相对强度 1.0"映射到与夜天光同量级的墙面照度。
///
/// 视觉效果：调大 → 夜里开灯的暖底更亮；调小 → 夜晚更冷清。
const double kIndoorLightScale = 0.6;

/// 月光的**珀金杰位移**（观察者模型：色度保留比例）。
///
/// 物理背景：月光 0.1~0.3 lux 处于中间视觉下段，视杆细胞（峰值 507 nm）
/// 主导、无色彩分辨能力——场景色彩感知大幅褪色。这是"银白月夜"的
/// 生理学来源：月面反射谱本身微偏红（月壤铁吸收，保留在光源光谱里
/// 不动），银白感来自**观察者降饱和**，不是月光真的偏蓝。
///
/// 实现：合成端对月光场景的饱和度乘以此系数（1.0 = 色彩保留）。
///
/// 视觉效果：调小（→0）→ 月夜完全褪成黑白"冷银"；调大（→1）→
/// 色彩保留，月光场景会显出材质本色（偏暖）——生理上不真实。
const double kMoonPurkinjeShift = 0.25;

/// 月光场景的**自动曝光目标缩放**（对显示中灰 0.18 的乘子）。
///
/// 物理背景：自动测光把月夜拉到中灰 = "月夜亮得像白天"。真实相机
/// 长曝月夜照片与暗适应人眼的感受都是**暗调**（Hunt 效应：低亮度级
/// 下感知明度整体下移）。满月夜照片中位亮度经验在中灰的 1/6~1/8。
///
/// 视觉效果：调大 → 月夜更亮（银白但失去夜感）；调小 → 更暗、
/// 光斑更突出（低钥匙 low-key）。
const double kMoonTargetScale = 0.30;

/// 无月夜空场景的自动曝光目标缩放。
///
/// 物理背景同上。无月夜更暗（仅气辉+星光），目标约中灰的 1/12。
///
/// 视觉效果：调大 → 星空夜可见更多室内细节；调小 → 近乎全黑只余
/// 窗外夜空辉光。
const double kNightTargetScale = 0.08;
